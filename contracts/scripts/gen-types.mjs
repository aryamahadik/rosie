#!/usr/bin/env node
// Contract types: `npm run contracts:types` runs `npm run types --workspace contracts` (T-006; ADR-005; build
// prompt 3.5(c)). ES module; uses json-schema-to-typescript from the root manifest.
//
// Writes one TypeScript module per schema into contracts/generated/, which is git-ignored and never committed or
// edited: contracts/<path>/<name>.v1.schema.json -> contracts/generated/<path>/<name>.v1.ts. The folder is emptied
// first, so a type whose schema is gone goes too. Meta-schemas (*.meta.schema.json) and the tools' own sample
// (contracts/scripts/) get no types. $refs resolve from the files on disk; nothing is fetched over the network.
//
// Usage: node scripts/gen-types.mjs [--out <dir>] [<schema file> ...]
//   default: every schema under contracts/ into contracts/generated/; with files, only those (paths inside contracts/).
// Exit code: 0 written, 1 failed.

import { mkdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compileFromFile } from "json-schema-to-typescript";

import { CONTRACTS_DIR, isMetaSchemaFile, isSchemaFile, listFiles } from "./lib.mjs";

const DEFAULT_OUT = path.join(CONTRACTS_DIR, "generated");

/** The schemas that get types: every *.schema.json except meta-schemas and the tools' own folder. */
export function typedSchemas(contractsDir = CONTRACTS_DIR) {
  return listFiles(contractsDir).filter(
    (file) => isSchemaFile(file) && !isMetaSchemaFile(file) && !file.startsWith("scripts/"),
  );
}

/** contracts-relative "common/formats.v1.schema.json" -> "common/formats.v1.ts". */
export const outputPath = (file) => file.replace(/\.schema\.json$/, ".ts");

/**
 * Compiles each schema (paths relative to contractsDir) into outDir. Returns the files written, relative to outDir.
 * @param {{ contractsDir?: string, outDir?: string, files?: string[] }} options
 */
export async function generateTypes({ contractsDir = CONTRACTS_DIR, outDir = DEFAULT_OUT, files } = {}) {
  const schemas = files ?? typedSchemas(contractsDir);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  const written = [];
  for (const file of schemas) {
    const absolute = path.join(contractsDir, file);
    const code = await compileFromFile(absolute, {
      cwd: path.dirname(absolute),
      bannerComment: `/* Generated by contracts/scripts/gen-types.mjs from contracts/${file}. Git-ignored: never edit or commit (ADR-005). */`,
      unreachableDefinitions: true,
      strictIndexSignatures: true,
      $refOptions: { resolve: { http: false } },
    });
    const target = outputPath(file);
    mkdirSync(path.dirname(path.join(outDir, target)), { recursive: true });
    writeFileSync(path.join(outDir, target), code);
    written.push(target);
  }
  return written;
}

/** Runs the generator; resolves to the exit code. */
export async function main(argv, { write = (line) => console.log(line) } = {}) {
  let outDir = DEFAULT_OUT;
  const files = [];
  for (let k = 0; k < argv.length; k += 1) {
    if (argv[k] === "--out" && argv[k + 1] !== undefined) {
      outDir = path.resolve(argv[k + 1]);
      k += 1;
    } else if (argv[k].startsWith("-")) {
      write(
        `FAIL unknown argument "${argv[k]}". Usage: node scripts/gen-types.mjs [--out <dir>] [<schema file> ...]`,
      );
      return 1;
    } else {
      files.push(path.relative(CONTRACTS_DIR, path.resolve(argv[k])).split(path.sep).join("/"));
    }
  }
  try {
    const written = await generateTypes({ outDir, ...(files.length > 0 ? { files } : {}) });
    write(
      `contract types: ${written.length} module(s) written to ${path.relative(process.cwd(), outDir) || "."}`,
    );
    for (const file of written) write(`  ${file}`);
    return 0;
  } catch (error) {
    write(`FAIL contract types: ${error.message}`);
    return 1;
  }
}

function runAsScript() {
  if (process.argv[1] === undefined) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (runAsScript()) process.exitCode = await main(process.argv.slice(2));
